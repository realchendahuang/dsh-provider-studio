/**
 * Build the Client half into the browser artifact the DSH client loader
 * expects: window.__ModuleLoader__.load({ id, factory(require) }).
 *
 * The JSX sources are bundled as CommonJS (React is external and resolved from
 * the loader's module table) and then wrapped in the factory, so the bundle's
 * `require('react')` calls receive the factory argument.
 */

import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bundlePath = resolve(root, 'dist', 'client.bundle.cjs')
const outputPath = resolve(root, 'client.js')

await mkdir(dirname(bundlePath), { recursive: true })

await build({
  absWorkingDir: root,
  entryPoints: [resolve(root, 'src/client/entry.jsx')],
  outfile: bundlePath,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'transform',
  external: ['react'],
  logLevel: 'warning',
})

const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

const code = await readFile(bundlePath, 'utf8')
const indented = code
  .split('\n')
  .map((line) => (line.length > 0 ? `    ${line}` : line))
  .join('\n')

const wrapper = `/** Generated by scripts/build-client.mjs — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    return module.exports;
  },
});
`

await writeFile(outputPath, wrapper, 'utf8')
console.log(`client.js written (${wrapper.length} bytes)`)
