/**
 * Build the Client half into the browser artifact the DSH client loader
 * expects: window.__ModuleLoader__.load({ id, factory(require) }).
 *
 * The JSX sources are bundled as CommonJS (React is external and resolved from
 * the loader's module table) and then wrapped in the factory, so the bundle's
 * `require('react')` calls receive the factory argument.
 *
 * `scripts/check.mjs` imports `renderClient()` to rebuild the exact same bytes
 * in memory (never touching the disk) and compare them with the committed
 * client.js. Keep the wrapper and the esbuild options in this file so the gate
 * cannot drift from the real build.
 *
 * Run: node scripts/build-client.mjs
 */

import { build, version as esbuildVersion } from 'esbuild'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const BUNDLE_PATH = resolve(ROOT, 'dist', 'client.bundle.cjs')
export const CLIENT_PATH = resolve(ROOT, 'client.js')

const WRAPPER_HEADER = '/** Generated by scripts/build-client.mjs — do not edit by hand. */'

/** esbuild options shared by the real build and the in-memory check rebuild. */
const BUILD_OPTIONS = {
  absWorkingDir: ROOT,
  entryPoints: [resolve(ROOT, 'src/client/entry.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'transform',
  external: ['react'],
}

/** Wrap the esbuild CJS bundle in the loader factory DSH expects. */
export function wrapBundle(code, pkgName) {
  const indented = code
    .split('\n')
    .map((line) => (line.length > 0 ? `    ${line}` : line))
    .join('\n')

  return `${WRAPPER_HEADER}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkgName)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    return module.exports;
  },
});
`
}

/**
 * Bundle `src/client/` and return the exact text of `client.js` without writing
 * anything to disk. Used by scripts/check.mjs for the stale-artifact gate.
 *
 * @param {{ pkg?: object, logLevel?: 'silent' | 'warning' }} [options]
 * @returns {Promise<{ bundle: string, wrapper: string, pkg: object }>}
 */
export async function renderClient({ pkg, logLevel = 'silent' } = {}) {
  const manifest = pkg ?? JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'))
  const result = await build({ ...BUILD_OPTIONS, outfile: BUNDLE_PATH, write: false, logLevel })
  const [output] = result.outputFiles
  return { bundle: output.text, wrapper: wrapBundle(output.text, manifest.name), pkg: manifest }
}

/** Build and write the artifacts: the `dist/` intermediate and the tracked client.js. */
export async function writeClient() {
  const { bundle, wrapper, pkg } = await renderClient({ logLevel: 'warning' })

  await mkdir(dirname(BUNDLE_PATH), { recursive: true })
  await writeFile(BUNDLE_PATH, bundle, 'utf8')

  // Atomic swap: a killed build must never leave a half-written client.js behind,
  // because the committed artifact is exactly what every install loads.
  const tmpPath = `${CLIENT_PATH}.tmp-${process.pid}`
  try {
    await writeFile(tmpPath, wrapper, 'utf8')
    await rename(tmpPath, CLIENT_PATH)
  } catch (error) {
    await rm(tmpPath, { force: true })
    throw error
  }

  console.log(
    `client.js written (${Buffer.byteLength(wrapper)} bytes, esbuild ${esbuildVersion}, ${pkg.name}@${pkg.version})`,
  )
  return wrapper
}

const invokedDirectly = process.argv[1] !== undefined
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url

if (invokedDirectly) {
  try {
    await writeClient()
  } catch (error) {
    console.error(`client build failed: ${error?.message ?? error}`)
    if (!existsSync(resolve(ROOT, 'node_modules/esbuild'))) {
      console.error('esbuild is not installed — run `npm ci` (or `npm install`) first.')
    } else if (Array.isArray(error?.errors) && error.errors.length > 0) {
      for (const item of error.errors) {
        const at = item.location ? ` (${item.location.file}:${item.location.line})` : ''
        console.error(`  ${item.text}${at}`)
      }
    }
    process.exitCode = 1
  }
}
