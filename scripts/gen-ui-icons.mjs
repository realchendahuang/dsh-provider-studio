/**
 * Bake the UI icon set used by the panel into `src/client/ui-icons.jsx`.
 *
 * Icons come from Lucide (https://lucide.dev, ISC) — the same family ZCode's
 * provider settings uses — so the strokes, caps and 24px grid match. The
 * generated module keeps only the inner geometry and renders it through one
 * shared <svg> wrapper, which keeps the bundle small and the styling uniform.
 *
 * Usage: node scripts/gen-ui-icons.mjs
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

// name in the panel → file downloaded from lucide-static
const ICONS = {
  'arrow-left': 'arrow-left',
  'chevron-right': 'chevron-right',
  'chevron-down': 'chevron-down',
  'chevron-up': 'chevron-up',
  plus: 'plus',
  x: 'x',
  check: 'check',
  'refresh-cw': 'refresh-cw',
  'trash-2': 'trash-2',
  pencil: 'pencil',
  unplug: 'unplug',
  search: 'search',
  eye: 'eye',
  'eye-off': 'eye-off',
  'more-horizontal': 'more-horizontal',
  'lock-keyhole': 'lock-keyhole',
  info: 'info',
  'circle-alert': 'circle-alert',
  'circle-check': 'circle-check',
  loader: 'loader-circle',
  package: 'package',
  copy: 'copy',
  download: 'download',
  sparkles: 'sparkles',
  'external-link': 'external-link',
  'grip-vertical': 'grip-vertical',
  'circle-help': 'circle-help',
}

const SOURCE_DIR = process.env.LUCIDE_DIR || '/tmp/lucide'

const entries = []
for (const [key, file] of Object.entries(ICONS)) {
  const svg = await readFile(resolve(SOURCE_DIR, `${file}.svg`), 'utf8')
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim()
  if (inner === '') throw new Error(`no geometry for ${file}`)
  entries.push(`  '${key}': '${inner.replace(/'/g, "\\'")}',`)
}

const module = `/** UI icons — generated by scripts/gen-ui-icons.mjs; do not edit by hand.
 *
 * Geometry from Lucide (https://lucide.dev), ISC licence. Stroke width, caps
 * and joins are applied by <Icon>, so every glyph in the panel has the same
 * weight as the rest of the interface.
 */

import React from 'react'

const GEOMETRY = {
${entries.join('\n')}
}

/** One lucide glyph, 24px grid, 1.75 stroke by default (ZCode's row icons). */
export function Icon({ name, size = 16, strokeWidth = 1.75, className, style }) {
  const geometry = GEOMETRY[name]
  if (geometry === undefined) return null
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className === undefined ? 'dpp-i' : \`dpp-i \${className}\`}
      style={style}
      aria-hidden="true"
      focusable="false"
      dangerouslySetInnerHTML={{ __html: geometry }}
    />
  )
}
`

await writeFile(resolve(root, 'src/client/ui-icons.jsx'), module, 'utf8')
console.log(`ui-icons.jsx written (${entries.length} icons)`)
